import sanitizeHtml from "sanitize-html";
export function cleanRichText(html: string): string {
    return sanitizeHtml(html, {
        allowedTags: [
            "p",
            "br",
            "strong",
            "b",
            "em",
            "i",
            "u",
            "s",
            "ul",
            "ol",
            "li",
            "blockquote",
            "pre",
            "code",
            "span",
            "h1",
            "h2",
            "h3",
            "h4",
            "h5",
            "h6",
            "a",
            "img",
            "table",
            "thead",
            "tbody",
            "tr",
            "th",
            "td",
        ],
        allowedAttributes: {
            "*": ["style"],
            a: ["href", "title"],
            img: ["src", "alt", "title", "width", "height"],
            td: ["colspan", "rowspan"],
            th: ["colspan", "rowspan"],
        },
        allowedStyles: {
            "*": {
                "text-align": [/^(left|right|center|justify)$/],
                color: [
                    /^#[0-9a-f]{3,8}$/i,
                    /^rgba?\([0-9.,%\s]+\)$/i,
                    /^(black|white|red|green|blue|gray|grey|transparent)$/i,
                ],
                "background-color": [
                    /^#[0-9a-f]{3,8}$/i,
                    /^rgba?\([0-9.,%\s]+\)$/i,
                    /^(black|white|red|green|blue|gray|grey|transparent)$/i,
                ],
                "font-size": [/^\d+(\.\d+)?(px|pt|em|rem|%)$/],
                "font-family": [/^[a-zA-Z0-9 ,"'-]+$/],
                width: [/^\d+(\.\d+)?(px|%)$/],
                height: [/^\d+(\.\d+)?(px|%)$/],
            },
        },
        allowedSchemesByTag: { img: ["http", "https"] },
        allowedSchemes: ["http", "https", "mailto"],
        allowProtocolRelative: false,
    });
}
